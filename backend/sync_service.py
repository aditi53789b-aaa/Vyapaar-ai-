def sync_government_schemes(db: Session) -> Dict[str, Any]:
    """
    Synchronizes the official schemes catalog with validation,
    ensuring foreign key linkage to official government sources.
    """
    # 1. Ensure sources exist
    init_government_sources(db)
    
    synced_count = 0
    created_count = 0
    updated_count = 0
    
    for item in VERIFIED_SCHEME_CATALOG:
        source_code = item.pop("source_code", None)
        source = None
        if source_code:
            source = get_source_by_code(db, source_code)
            
        existing = db.query(GovernmentScheme).filter(GovernmentScheme.scheme_code == item["scheme_code"]).first()
        if not existing:
            scheme = GovernmentScheme(
                source_id=source.id if source else None,
                verification_date=datetime.now(timezone.utc),
                is_active=True,
                **item
            )
            db.add(scheme)
            created_count += 1
        else:
            for k, v in item.items():
                setattr(existing, k, v)
            existing.source_id = source.id if source else existing.source_id
            existing.verification_date = datetime.now(timezone.utc)
            existing.is_active = True
            updated_count += 1
            
        synced_count += 1
        # Restore source_code for idempotent runs
        item["source_code"] = source_code

    db.commit()
    return {
        "status": "SUCCESS",
        "total_synced": synced_count,
        "created": created_count,
        "updated": updated_count,
        "timestamp": datetime.now(timezone.utc).isoformat()
    }
